using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Game.Core.DevTools
{
    /// <summary>One laid-out view: which fixture, on which device.</summary>
    public sealed class LayoutCase
    {
        public string Fixture { get; }
        public string Device { get; }
        public LayoutRect Canvas { get; }
        public LayoutRect SafeArea { get; }
        public LayoutNode Root { get; }

        public LayoutCase(string fixture, string device, LayoutRect canvas, LayoutRect safeArea, LayoutNode root)
        {
            Fixture = fixture;
            Device = device;
            Canvas = canvas;
            SafeArea = safeArea;
            Root = root;
        }

        public string Key => Fixture + "@" + Device;
    }

    /// <summary>
    /// Text "screenshot" of a view: every active node's rect, one line each. Deterministic (no GPU, no font
    /// rasterizer), diff-friendly and cheap to read: a 2px move is exactly one changed line.
    /// Texts are NOT recorded (copy changes are not layout changes; the TEXT check covers clipping).
    /// </summary>
    public static class LayoutSnapshot
    {
        public const string Header = "# layout snapshot v1";

        public static string Render(string viewId, IEnumerable<LayoutCase> cases)
        {
            var sb = new StringBuilder();
            sb.Append(Header).Append(": ").Append(viewId).Append('\n');
            sb.Append("# Generated by the layout gate. Owners regenerate with LAYOUT_WRITE=1 and review the diff; never edit by hand.\n");
            foreach (var c in cases.OrderBy(c => c.Key, StringComparer.Ordinal))
            {
                sb.Append("== ").Append(c.Key).Append(" canvas=").Append(c.Canvas.W).Append('x').Append(c.Canvas.H)
                  .Append(" safe=").Append(c.SafeArea).Append('\n');
                foreach (var n in c.Root.Descendants())
                    sb.Append(n.Path).Append(' ').Append(KindCode(n.Kind)).Append(' ').Append(n.Rect).Append('\n');
            }
            return sb.ToString();
        }

        /// <summary>
        /// Human/agent-readable differences, keyed by case + node path, e.g.
        /// "smoke@phone-16x9 Background/Question: 60,520 960x400 -> 60,519 960x402". Empty = identical.
        /// </summary>
        public static List<string> Diff(string expected, string actual, int max = 20)
        {
            var e = Parse(expected);
            var a = Parse(actual);
            var result = new List<string>();
            foreach (var key in e.Keys.Union(a.Keys).OrderBy(k => k, StringComparer.Ordinal))
            {
                e.TryGetValue(key, out var ev);
                a.TryGetValue(key, out var av);
                if (ev == av)
                    continue;
                result.Add(ev == null ? key + ": added " + av : av == null ? key + ": removed (was " + ev + ")" : key + ": " + ev + " -> " + av);
            }
            if (result.Count > max)
            {
                int more = result.Count - max;
                result = result.Take(max).ToList();
                result.Add("... and " + more + " more");
            }
            return result;
        }

        private static Dictionary<string, string> Parse(string text)
        {
            var map = new Dictionary<string, string>(StringComparer.Ordinal);
            string section = "";
            foreach (var raw in (text ?? "").Replace("\r\n", "\n").Split('\n'))
            {
                string line = raw.TrimEnd();
                if (line.Length == 0 || line.StartsWith("#", StringComparison.Ordinal))
                    continue;
                if (line.StartsWith("== ", StringComparison.Ordinal))
                {
                    int sp = line.IndexOf(' ', 3);
                    section = sp < 0 ? line.Substring(3) : line.Substring(3, sp - 3);
                    map[section + " (canvas)"] = sp < 0 ? "" : line.Substring(sp + 1);
                    continue;
                }
                int k = line.IndexOf(' ');
                if (k <= 0)
                    continue;
                map[section + " " + line.Substring(0, k)] = line.Substring(k + 1);
            }
            return map;
        }

        private static char KindCode(LayoutNodeKind kind)
        {
            switch (kind)
            {
                case LayoutNodeKind.Decoration: return 'D';
                case LayoutNodeKind.Text: return 'T';
                case LayoutNodeKind.Interactive: return 'I';
                default: return 'C';
            }
        }
    }
}
