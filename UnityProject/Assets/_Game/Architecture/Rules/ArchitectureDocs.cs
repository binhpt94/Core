using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace Game.Architecture.Rules
{
    /// <summary>
    /// Renders the generated docs from <see cref="ArchitectureGraph"/>. Built to stay small as the game grows:
    ///   Docs/Architecture/overview.md        L1 + compact feature table (+ L2 only while it is readable)
    ///   Docs/Architecture/Features/F.md      one page per feature: 1-hop diagram, public face, states, DI
    /// Agents read the overview, then only the page of the feature they touch. All files are compared by ARCH090.
    /// </summary>
    public static class ArchitectureDocs
    {
        public const string Dir = "Docs/Architecture";
        public const string OverviewPath = Dir + "/overview.md";
        public const string FeaturesDir = Dir + "/Features";
        public const string GeneratedHeader = "<!-- GENERATED by ./Tools/test-gate.sh graph --write (or Unity: Tools > Game > Regenerate System Map) · do not edit · stale = ARCH090 -->";

        /// <summary>Above this many edges the full L2 diagram is unreadable (and costly); the overview summarises instead.</summary>
        public const int MaxOverviewEdges = 60;

        /// <summary>Above this many features L1 shows one "Features" node (the table lists them).</summary>
        public const int MaxL1Features = 30;

        public static string FeaturePagePath(string feature) => FeaturesDir + "/" + feature + ".md";

        /// <summary>Every generated file (repo-relative path → content).</summary>
        public static SortedDictionary<string, string> Render(ArchitectureGraph g, int maxOverviewEdges = MaxOverviewEdges)
        {
            var files = new SortedDictionary<string, string>(StringComparer.Ordinal) { [OverviewPath] = RenderOverview(g, maxOverviewEdges) };
            foreach (var f in g.Features.Keys)
                files[FeaturePagePath(f)] = RenderFeaturePage(g, f);
            return files;
        }

        /// <summary>Writes all generated files, deletes pages of removed features. Returns changed paths.</summary>
        public static List<string> WriteAll(string root)
        {
            var g = ArchitectureGraph.Build(root);
            var files = Render(g);
            var changed = new List<string>();
            foreach (var kv in files)
            {
                string full = Path.Combine(root, kv.Key);
                Directory.CreateDirectory(Path.GetDirectoryName(full));
                if (!File.Exists(full) || Normalize(File.ReadAllText(full)) != kv.Value)
                {
                    File.WriteAllText(full, kv.Value);
                    changed.Add(kv.Key);
                }
            }
            foreach (var orphan in OrphanPages(root, files))
            {
                File.Delete(Path.Combine(root, orphan));
                changed.Add(orphan + " (deleted)");
            }
            return changed;
        }

        public static IEnumerable<string> OrphanPages(string root, SortedDictionary<string, string> expected)
        {
            string dir = Path.Combine(root, FeaturesDir);
            if (!Directory.Exists(dir))
                yield break;
            foreach (var f in Directory.GetFiles(dir, "*.md"))
            {
                string rel = PathInfo.Normalize(f.Substring(root.Length));
                if (!expected.ContainsKey(rel))
                    yield return rel;
            }
        }

        public static string Normalize(string s) => s.Replace("\r\n", "\n");

        // ------------------------------------------------------------------ overview

        public static string RenderOverview(ArchitectureGraph g, int maxOverviewEdges = MaxOverviewEdges)
        {
            var sb = new StringBuilder();
            sb.Append(GeneratedHeader).Append("\n# System map\n\n");
            sb.Append("Derived from `.asmdef` files, source, `Transition<TState>` tables and `Tools/ArchitecturePolicy.txt`.\n");
            sb.Append("Per feature: `Docs/Architecture/Features/<F>.md`. Queries: `./Tools/test-gate.sh graph feature|impact|di <F>`, `graph diff`.\n\n");

            // L1
            sb.Append("## L1 · System\n\n```mermaid\nflowchart LR\n");
            bool collapsed = g.Features.Count > MaxL1Features;
            sb.Append("  Bootstrap[Bootstrap] -->|wires| Features\n");
            if (collapsed)
                sb.Append("  Features[").Append(g.Features.Count).Append(" features: see table]\n");
            else
            {
                sb.Append("  subgraph Features\n");
                foreach (var f in g.Features.Keys)
                    sb.Append("    ").Append(Id(f)).Append('[').Append(f).Append("]\n");
                sb.Append("  end\n");
            }
            sb.Append("  Features --> Core[Core]\n");
            foreach (var v in g.Policy.Vendors.OrderBy(v => v.Id, StringComparer.Ordinal))
            {
                if (!g.VendorUsers.TryGetValue(v.Id, out var users))
                    continue;
                sb.Append("  ").Append(Id("v_" + v.Id)).Append("[(").Append(v.Id).Append(" · ").Append(v.Tier.ToString().ToLowerInvariant()).Append(")]\n");
                var groups = users.Select(x => g.Features.ContainsKey(x.Replace(".Contracts", "")) ? x.Replace(".Contracts", "") : x).Distinct().ToList();
                if (groups.Count > 8 || collapsed)
                    sb.Append("  Features -.->|").Append(groups.Count).Append(" users| ").Append(Id("v_" + v.Id)).Append('\n');
                else
                    foreach (var u in groups)
                        sb.Append("  ").Append(Id(u)).Append(" -.-> ").Append(Id("v_" + v.Id)).Append('\n');
            }
            sb.Append("```\n\n");

            // L2 (only while readable)
            sb.Append("## L2 · Feature dependencies\n\n");
            if (g.Edges.Count <= maxOverviewEdges)
            {
                sb.Append("Solid = compile-time (`uses`, `wires`), dotted = runtime implementation of a contract.\n\n```mermaid\nflowchart LR\n");
                foreach (var e in g.Edges)
                    sb.Append("  ").Append(Edge(e)).Append('\n');
                sb.Append("```\n\n");
            }
            else
            {
                sb.Append(g.Edges.Count).Append(" edges: too many for one readable diagram. See each feature page (1-hop diagram) and `graph impact <F>`.\n\n");
                sb.Append("Most depended-on:\n\n| Node | Used by |\n|---|---|\n");
                foreach (var top in g.Edges.Where(e => e.Kind != "implements").GroupBy(e => e.To)
                             .OrderByDescending(x => x.Count()).ThenBy(x => x.Key, StringComparer.Ordinal).Take(15))
                    sb.Append("| ").Append(top.Key).Append(" | ").Append(top.Count()).Append(" |\n");
                sb.Append('\n');
            }

            // Compact feature table (details live on feature pages)
            sb.Append("## Features\n\n| Feature | Uses | Used by | Vendors | States | Tests |\n|---|---|---|---|---|---|\n");
            foreach (var f in g.Features.Values)
            {
                var usedBy = g.FeatureUsedBy(f.Name).ToList();
                sb.Append("| [").Append(f.Name).Append("](features/").Append(f.Name).Append(".md) | ")
                  .Append(ArchitectureGraph.List(g.FeatureUses(f.Name))).Append(" | ")
                  .Append(usedBy.Count > 5 ? usedBy.Count + " features" : ArchitectureGraph.List(usedBy)).Append(" | ")
                  .Append(ArchitectureGraph.List(f.Vendors)).Append(" | ")
                  .Append(g.StateMachines.Count(s => s.Feature == f.Name)).Append(" | ").Append(f.Tests).Append(" |\n");
            }

            // Third-party
            sb.Append("\n## Third-party\n\n| Vendor | Tier | Assemblies | Allowed in | Used by | Pinned by |\n|---|---|---|---|---|---|\n");
            foreach (var v in g.Policy.Vendors.OrderBy(v => v.Id, StringComparer.Ordinal))
            {
                string allowed = v.Tier == VendorTier.Foundation ? "everywhere" : v.Tier == VendorTier.Presentation ? "Unity layers" : v.Adapter + " only";
                string users = g.VendorUsers.TryGetValue(v.Id, out var u) ? (u.Count > 5 ? u.Count + " assemblies" : string.Join(", ", u)) : "-";
                string pin = !string.IsNullOrEmpty(v.Package) ? "package " + v.Package + "@" + v.Version : "sha256 of " + v.Source;
                sb.Append("| ").Append(v.Id).Append(" | ").Append(v.Tier.ToString().ToLowerInvariant()).Append(" | ").Append(string.Join(", ", v.Assemblies))
                  .Append(" | ").Append(allowed).Append(" | ").Append(users).Append(" | ").Append(pin).Append(" |\n");
            }
            if (!g.AssetsKnown)
                sb.Append("\n> Asset references: **UNKNOWN** until Unity has generated `.meta` files (open the project once). Any asset without its `.meta` fails ARCH084.\n");
            return sb.ToString();
        }

        // ------------------------------------------------------------------ feature page

        public static string RenderFeaturePage(ArchitectureGraph g, string name)
        {
            var f = g.Features[name];
            var sb = new StringBuilder();
            sb.Append(GeneratedHeader).Append("\n# Feature: ").Append(name).Append("\n\n");
            sb.Append("Hand-written intent and invariants: `Assets/_Game/Features/").Append(name).Append("/README.md`. Back to the [system map](../overview.md).\n\n");

            sb.Append("## Dependencies (1 hop)\n\n```mermaid\nflowchart LR\n");
            var local = g.Edges.Where(e => Is(e.From, name) || Is(e.To, name)).ToList();
            if (local.Count == 0)
                sb.Append("  ").Append(Id(name)).Append('[').Append(name).Append("]\n");
            foreach (var e in local)
                sb.Append("  ").Append(Edge(e)).Append('\n');
            sb.Append("```\n\n");

            sb.Append("| | |\n|---|---|\n");
            sb.Append("| Uses | ").Append(ArchitectureGraph.List(g.FeatureUses(name))).Append(" |\n");
            sb.Append("| Used by | ").Append(ArchitectureGraph.List(g.FeatureUsedBy(name))).Append(" |\n");
            sb.Append("| Implements | ").Append(ArchitectureGraph.List(g.Edges.Where(e => e.From == name && e.Kind == "implements").Select(e => e.To))).Append(" |\n");
            sb.Append("| Implemented by | ").Append(ArchitectureGraph.List(g.Edges.Where(e => e.To == name + ".Contracts" && e.Kind == "implements").Select(e => e.From))).Append(" |\n");
            sb.Append("| Public face | ").Append(ArchitectureGraph.List(f.PublicTypes)).Append(" |\n");
            sb.Append("| Vendors | ").Append(ArchitectureGraph.List(f.Vendors)).Append(" |\n");
            sb.Append("| Assets (Public/Private) | ").Append(f.PublicAssets).Append('/').Append(f.PrivateAssets).Append(g.AssetsKnown ? "" : " (refs UNKNOWN: no .meta yet)").Append(" |\n");
            sb.Append("| Tests | ").Append(f.Tests).Append(" |\n");

            foreach (var sm in g.StateMachines.Where(s => s.Feature == name))
            {
                sb.Append("\n## State machine: ").Append(sm.Owner).Append('.').Append(sm.Table).Append(" (").Append(sm.Enum).Append(")\n\n");
                sb.Append("Generated from the `Transition<").Append(sm.Enum).Append(">` table that the code enforces at runtime.\n\n```mermaid\nstateDiagram-v2\n");
                sb.Append("  [*] --> ").Append(sm.Transitions[0].From).Append('\n');
                foreach (var t in sm.Transitions)
                    sb.Append("  ").Append(t.From).Append(" --> ").Append(t.To).Append(" : ").Append(t.Trigger).Append('\n');
                sb.Append("```\n");
            }

            sb.Append("\n## Constructor injection (L3)\n\n```text\n").Append(ArchitectureGraph.DescribeDependencyInjection(g.Root, name)).Append("\n```\n");
            return sb.ToString();
        }

        private static bool Is(string group, string feature) => group == feature || group == feature + ".Contracts";

        private static string Edge(ArchitectureGraph.Edge e) =>
            Id(e.From) + "[" + e.From + "]" + (e.Kind == "implements" ? " -.->|implements| " : " -->|" + e.Kind + "| ") + Id(e.To) + "[" + e.To + "]";

        private static string Id(string name) => Regex.Replace(name, @"[^A-Za-z0-9]", "_");
    }
}
